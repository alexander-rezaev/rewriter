def format_terms_block(terms: list[str]) -> str:
    if not terms:
        return ""
    listed = "; ".join(terms)
    return (
        "\nСловарь терминов — пиши каждый термин ТОЧНО в этом виде, "
        "без расшифровки, перевода и синонимов: "
        f"{listed}.\n"
    )


def build_user_prompt(
    text: str,
    style: Style,
    terms: list[str] | None = None,
    context: str = "",
    facts: list[str] | None = None,
    dropped: list[str] | None = None,
) -> str:
    previous = ""
    if context.strip():
        previous = (
            "Последние предложения предыдущей части уже переписаны. Не копируй их. "
            "Продолжай в том же стиле:\n"
            f"{context.strip()}\n\n"
        )
    kept = [fact.strip() for fact in (facts or []) if fact and fact.strip()]
    lost = [fact.strip() for fact in (dropped or []) if fact and fact.strip()]
    fact_block = ""
    if lost:
        fact_block += (
            "Прошлая попытка потеряла эти написания. Повтори переписывание и сохрани их дословно:\n"
            + "; ".join(lost)
            + "\n\n"
        )
    if kept:
        fact_block += (
            "Сохрани точно эти написания, числа, даты и коды. Не сокращай и не опускай их:\n"
            + "; ".join(kept)
            + "\n\n"
        )
    return (
        f"Стиль: {style.name}\n"
        f"Инструкция по стилю: {style.instruction}\n"
        f"{format_terms_block(terms or [])}\n"
        f"{previous}"
        f"{fact_block}"
        f"Исходный текст:\n{text}"
    )


def build_source_prompt(text: str, terms: list[str] | None = None) -> str:
    terms_block = format_terms_block(terms or [])
    if terms_block:
        return f"{terms_block.strip()}\n\nИсходный текст:\n{text}"
    return f"Исходный текст:\n{text}"


def build_proofread_prompt(text: str, terms: list[str] | None = None, context: str = "") -> str:
    body = build_source_prompt(text, terms)
    if not context.strip():
        return body
    return (
        "Предыдущий фрагмент уже проверен. Не включай его в ответ, "
        "он нужен только чтобы не потерять связь предложений:\n"
        f"{context.strip()}\n\n"
        f"{body}"
    )


def build_grammar_prompt(text: str, terms: list[str] | None = None) -> str:
    return build_source_prompt(text, terms)
